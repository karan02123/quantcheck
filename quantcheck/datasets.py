"""Fetch real public benchmark subsets and cache them as QuantCheck JSONL suites.

WHY THIS EXISTS
--------------
The bundled JSONL files in quantcheck/suites/ started as hand-authored prompts
in the *style* of GSM8K/MMLU — honest about that provenance (see
quantcheck/suites/SOURCE.md) — but not the real thing. "Style I wrote" != "samples from the actual benchmark," and only
the latter lets a user trust the verdict maps to numbers others have measured.

This module fetches a fixed, seeded, reproducible subset of each real benchmark
via HuggingFace ``datasets``, converts to QuantCheck JSONL format, and writes
into quantcheck/suites/ — overwriting the hand-authored files. After running
this once the existing loader, scorer, and runner are unchanged; only the provenance improves.

BENCHMARKS
----------
reasoning  -> GSM8K (test split, Cobbe et al. 2021, arXiv:2110.14168)
             Numeric word problems. Answer extracted after "####" delimiter.
             Apache-2.0 licensed.

knowledge  -> MMLU (test split, Hendrycks et al. 2021, arXiv:2009.03300)
             4-option multiple choice across diverse subjects. MIT licensed.
             We sample uniformly from a curated subject list for topic variety.

instruction -> Skipped for real-benchmark replacement. IFEval's verifier
             functions are complex Python code, not reducible to keyword
             presence — replacing with a real subset would require shipping
             those verifiers, which changes the scoring contract. The
             hand-authored instruction suite stays, documented as such.

DETERMINISM
-----------
The same (benchmark, n_items, seed) triple always produces the same prompt set —
logged in the header comment of each generated JSONL so the selection is
reproducible and auditable. The seed is NOT a model seed; it's just for sampling.
"""

from __future__ import annotations

import json
import random
import textwrap
from pathlib import Path
from typing import Iterator

__all__ = [
    "fetch_gsm8k",
    "fetch_mmlu",
    "fetch_and_write_all",
]

_SUITES_DIR = Path(__file__).resolve().parent / "suites"

# MMLU subjects to sample from — broad topic coverage without
# overcounting any one domain.
_MMLU_SUBJECTS = [
    "high_school_mathematics",
    "college_mathematics",
    "abstract_algebra",
    "high_school_world_history",
    "world_religions",
    "high_school_geography",
    "high_school_biology",
    "high_school_chemistry",
    "high_school_physics",
    "high_school_computer_science",
    "computer_security",
    "logical_fallacies",
    "formal_logic",
    "high_school_statistics",
]


def _import_datasets():
    try:
        import datasets  # noqa: PLC0415
        return datasets
    except ImportError as e:
        raise ImportError(
            "fetching real benchmark suites requires the 'datasets' package:\n"
            "    pip install datasets\n"
            f"(original error: {e})"
        ) from e


def _header(benchmark: str, split: str, n: int, seed: int) -> str:
    return (
        f"# AUTO-GENERATED by quantcheck fetch-suites — DO NOT EDIT MANUALLY\n"
        f"# benchmark={benchmark!r}  split={split!r}  n={n}  seed={seed}\n"
        f"# Re-generate: quantcheck fetch-suites\n"
    )


# --------------------------------------------------------------------------- #
# GSM8K -> reasoning.jsonl
# --------------------------------------------------------------------------- #
def _extract_gsm8k_answer(answer_text: str) -> str | None:
    """Extract the numeric answer after the '####' delimiter in GSM8K answers.

    GSM8K format: "... chain of thought ...\n#### 72"
    Returns the number string, or None if not found.
    """
    for line in reversed(answer_text.split("\n")):
        if "####" in line:
            num = line.split("####")[-1].strip().replace(",", "")
            return num
    return None


def fetch_gsm8k(n: int = 200, seed: int = 42, split: str = "test") -> list[dict]:
    """Fetch ``n`` items from GSM8K and return as QuantCheck JSONL dicts.

    Args:
        n: number of items to sample. GSM8K test split has 1319 items.
        seed: random seed for reproducible sampling.
        split: dataset split ("test" recommended; also "train" for more volume).

    Returns:
        List of dicts with keys: prompt, answer, scorer, task.

    Raises:
        ImportError: if ``datasets`` is not installed.
        ValueError: if fewer than ``n`` parseable items are found in the split.
    """
    ds = _import_datasets()
    dataset = ds.load_dataset("openai/gsm8k", "main", split=split, trust_remote_code=False)
    rng = random.Random(seed)
    indices = list(range(len(dataset)))
    rng.shuffle(indices)

    items = []
    skipped = 0
    for i in indices:
        if len(items) >= n:
            break
        row = dataset[i]
        answer = _extract_gsm8k_answer(row["answer"])
        if answer is None:
            skipped += 1
            continue
        prompt = (
            row["question"].strip()
            + "\n\nSolve step by step, then write your final answer as: #### <number>"
        )
        items.append({
            "prompt": prompt,
            "answer": answer,
            "scorer": "numeric",
            "task": "arithmetic",
        })

    if len(items) < n:
        raise ValueError(
            f"GSM8K {split} split yielded only {len(items)} parseable items "
            f"(skipped {skipped}); requested {n}."
        )
    return items


# --------------------------------------------------------------------------- #
# MMLU -> knowledge.jsonl
# --------------------------------------------------------------------------- #
_LETTERS = "ABCD"


def _format_mmlu_prompt(question: str, choices: list[str]) -> str:
    options = "\n".join(f"{_LETTERS[i]}) {c}" for i, c in enumerate(choices))
    return f"{question.strip()}\n{options}\nAnswer:"


def _mmlu_items(ds_module, subject: str, split: str, rng: random.Random,
                budget: int) -> list[dict]:
    """Load up to ``budget`` items from one MMLU subject."""
    try:
        dataset = ds_module.load_dataset(
            "cais/mmlu", subject, split=split, trust_remote_code=False
        )
    except Exception:  # noqa: BLE001 — some subjects may not have a test split
        return []
    rows = list(dataset)
    rng.shuffle(rows)
    items = []
    for row in rows[:budget]:
        choices = row["choices"]
        if len(choices) != 4:
            continue
        answer_idx = int(row["answer"])
        if not (0 <= answer_idx < 4):
            continue
        items.append({
            "prompt": _format_mmlu_prompt(row["question"], choices),
            "answer": _LETTERS[answer_idx],
            "scorer": "multiple_choice",
            "task": subject.replace("_", "-"),
        })
    return items


def fetch_mmlu(
    n: int = 200,
    seed: int = 42,
    split: str = "test",
    subjects: list[str] | None = None,
) -> list[dict]:
    """Fetch ``n`` items from MMLU (balanced across subjects) as JSONL dicts.

    Args:
        n: total items to return.
        seed: for reproducible sampling within each subject.
        split: dataset split ("test" or "validation" — MMLU has no public train
            answers; use "validation" for more data per subject).
        subjects: list of MMLU subject names; defaults to ``_MMLU_SUBJECTS``.

    Returns:
        List of dicts with keys: prompt, answer, scorer, task.

    Raises:
        ImportError: if ``datasets`` is not installed.
        ValueError: if fewer than ``n`` items can be collected.
    """
    ds = _import_datasets()
    subjects = subjects or _MMLU_SUBJECTS
    rng = random.Random(seed)
    per_subject = max(1, (n + len(subjects) - 1) // len(subjects))

    all_items: list[dict] = []
    for subj in subjects:
        all_items.extend(_mmlu_items(ds, subj, split, rng, per_subject))

    rng.shuffle(all_items)
    if len(all_items) < n:
        raise ValueError(
            f"MMLU yielded only {len(all_items)} items across {len(subjects)} "
            f"subjects (split={split!r}); requested {n}. "
            f"Try split='validation' for more, or reduce n."
        )
    return all_items[:n]


# --------------------------------------------------------------------------- #
# Write suites to disk
# --------------------------------------------------------------------------- #
def _write_jsonl(path: Path, items: list[dict], header: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        fh.write(header)
        for item in items:
            fh.write(json.dumps(item, ensure_ascii=False) + "\n")


def fetch_and_write_all(
    n_reasoning: int = 200,
    n_knowledge: int = 200,
    seed: int = 42,
    out_dir: Path | None = None,
    verbose: bool = True,
) -> dict[str, Path]:
    """Fetch real benchmark subsets and write them as bundled suite JSONL files.

    This overwrites quantcheck/suites/reasoning.jsonl and
    quantcheck/suites/knowledge.jsonl with real public benchmark samples.
    quantcheck/suites/instruction.jsonl is left unchanged (see
    module docstring for why).

    Args:
        n_reasoning: items to fetch from GSM8K (default 200).
        n_knowledge: items to fetch from MMLU (default 200).
        seed: sampling seed (logged in the JSONL header for reproducibility).
        out_dir: where to write; defaults to quantcheck/suites/ inside the
            package. On a non-editable install that directory may not be
            writable, so pass --out-dir and point --suite at the result.
        verbose: print progress.

    Returns:
        Dict mapping suite name to written path.

    Raises:
        ImportError: if ``datasets`` is not installed.
        ValueError: if a benchmark yields fewer items than requested.
    """
    out = out_dir or _SUITES_DIR
    written: dict[str, Path] = {}

    if verbose:
        print("Fetching GSM8K (reasoning)...")
    reasoning_items = fetch_gsm8k(n=n_reasoning, seed=seed, split="test")
    p = out / "reasoning.jsonl"
    _write_jsonl(p, reasoning_items, _header("openai/gsm8k/main", "test", n_reasoning, seed))
    written["reasoning"] = p
    if verbose:
        print(f"  wrote {len(reasoning_items)} items -> {p}")

    if verbose:
        print("Fetching MMLU (knowledge)...")
    knowledge_items = fetch_mmlu(n=n_knowledge, seed=seed, split="test")
    p = out / "knowledge.jsonl"
    _write_jsonl(p, knowledge_items, _header("cais/mmlu", "test", n_knowledge, seed))
    written["knowledge"] = p
    if verbose:
        print(f"  wrote {len(knowledge_items)} items -> {p}")

    if verbose:
        print(
            "Skipping instruction suite (hand-authored; IFEval verifiers not "
            "reducible to keyword scoring — see quantcheck/suites/SOURCE.md)."
        )

    return written
